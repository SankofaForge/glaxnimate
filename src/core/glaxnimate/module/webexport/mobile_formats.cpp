#include "mobile_formats.hpp"

#include <QRegularExpression>

#include "glaxnimate/io/lottie/lottie_format.hpp"

using namespace glaxnimate;

std::unique_ptr<settings::SettingsGroup> webexport::MobileComponentFormat::save_settings(model::Composition*) const
{
    return std::make_unique<settings::SettingsGroup>(settings::SettingList{
        settings::Setting("component_name", i18n("Component name"), i18n("Name of the generated component, starting with an uppercase letter"), QString("GlaxnimateAnimation")),
        settings::Setting("autoplay", i18n("Autoplay"), i18n("Start playing when the component appears"), true),
        settings::Setting("loop", i18n("Loop"), i18n("Repeat the animation"), true),
        settings::Setting("strip", i18n("Strip"), i18n("Strip unused Lottie properties to reduce size"), false),
    });
}

bool webexport::MobileComponentFormat::on_save(QIODevice& file, const QString&, model::Composition* comp, const QVariantMap& options)
{
    const QString name = options.value("component_name", QString("GlaxnimateAnimation")).toString();
    static const QRegularExpression valid_name("^[A-Z][A-Za-z0-9]{0,63}$");
    if ( !valid_name.match(name).hasMatch() )
    {
        error(i18n("The component name must start with an uppercase letter and contain at most 64 letters or digits"));
        return false;
    }

    io::lottie::LottieFormat lottie;
    connect(&lottie, &io::ImportExport::message, this, &io::ImportExport::message);
    QByteArray json = lottie.save(comp, {
        {"pretty", false},
        {"strip", options.value("strip", false).toBool()},
        {"auto_embed", true},
    });
    if ( json.isEmpty() )
    {
        error(i18n("Could not convert the animation to Lottie"));
        return false;
    }

    file.write(component(name, json, options.value("autoplay", true).toBool(), options.value("loop", true).toBool()));
    return true;
}

QByteArray webexport::ReactNativeFormat::component(const QString& name, const QByteArray& json, bool autoplay, bool loop) const
{
    QString source = QStringLiteral(
        "// Generated by Glaxnimate. Requires the lottie-react-native package.\n"
        "import React from 'react';\n"
        "import LottieView from 'lottie-react-native';\n"
        "\n"
        "const animationData = %1;\n"
        "\n"
        "export default function %2(props) {\n"
        "  return React.createElement(LottieView, {source: animationData, autoPlay: %3, loop: %4, ...props});\n"
        "}\n"
    );
    return source.arg(QString::fromUtf8(json), name, autoplay ? "true" : "false", loop ? "true" : "false").toUtf8();
}

QByteArray webexport::FlutterFormat::component(const QString& name, const QByteArray& json, bool autoplay, bool loop) const
{
    QString source = QStringLiteral(
        "// Generated by Glaxnimate. Requires the lottie package.\n"
        "import 'dart:convert';\n"
        "\n"
        "import 'package:flutter/widgets.dart';\n"
        "import 'package:lottie/lottie.dart';\n"
        "\n"
        "final _animationBytes = base64Decode('%1');\n"
        "\n"
        "class %2 extends StatelessWidget {\n"
        "  const %2({super.key, this.controller, this.animate = %3, this.repeat = %4, this.width, this.height});\n"
        "\n"
        "  final Animation<double>? controller;\n"
        "  final bool animate;\n"
        "  final bool repeat;\n"
        "  final double? width;\n"
        "  final double? height;\n"
        "\n"
        "  @override\n"
        "  Widget build(BuildContext context) {\n"
        "    return Lottie.memory(_animationBytes, controller: controller, animate: animate, repeat: repeat, width: width, height: height);\n"
        "  }\n"
        "}\n"
    );
    return source.arg(QString::fromLatin1(json.toBase64()), name, autoplay ? "true" : "false", loop ? "true" : "false").toUtf8();
}
